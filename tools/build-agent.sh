#!/bin/sh
# tools/build-agent.sh — build aeo-agent CARRYING Aether's sandbox preload
# library, so a fleet host needs the one binary and nothing beside it.
#
#   sh tools/build-agent.sh -o OUT [extra `ae build` args…]
#   AE_CC="gcc -static" sh tools/build-agent.sh -o aeo-agent-linux-x86_64-static
#
# It copies lib/ to a scratch dir, regenerates lib/sandbox_preload_blob there
# from THIS toolchain's libaether_sandbox.so (so the library always matches the
# runtime being linked in), and runs `ae build` against the copy. The repo tree
# is never touched — the committed blob module stays the empty stub.
#
# Linux only, native builds only: the library must be for the machine the agent
# will run on, and the toolchain only has its own. Elsewhere (or with --target)
# use plain `ae build bin/aeo-agent.ae`; that agent carries no library and
# grant-list confinement refuses to start there anyway.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
[ "${1:-}" = "-o" ] && [ -n "${2:-}" ] || { echo "usage: build-agent.sh -o OUT [ae build args…]" >&2; exit 2; }
OUT="$2"; shift 2

[ "$(uname -s)" = "Linux" ] || { echo "build-agent.sh: Linux only (plain 'ae build' elsewhere)" >&2; exit 2; }
for a in "$@"; do
    case "$a" in --target*) echo "build-agent.sh: no --target — the embedded library is this machine's" >&2; exit 2;; esac
done

# Find the library the way the runtime does: AETHER_SANDBOX_PRELOAD, else under
# the toolchain root (the directory above `ae`, resolved through symlinks).
SO="${AETHER_SANDBOX_PRELOAD:-}"
if [ -z "$SO" ]; then
    AE_BIN="$(readlink -f "$(command -v ae)")"
    AE_ROOT="$(dirname "$(dirname "$AE_BIN")")"
    for d in lib/aether lib build; do
        [ -f "$AE_ROOT/$d/libaether_sandbox.so" ] && { SO="$AE_ROOT/$d/libaether_sandbox.so"; break; }
    done
fi
[ -n "$SO" ] && [ -f "$SO" ] || { echo "build-agent.sh: cannot find libaether_sandbox.so (set AETHER_SANDBOX_PRELOAD)" >&2; exit 1; }

SHA="$(sha256sum "$SO" | cut -d' ' -f1)"
VER="$(ae version 2>/dev/null | head -1 | awk '{print $2}')"
FROM="ae ${VER:-unknown} linux-$(uname -m)"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
cp -R "$ROOT/lib" "$WORK/lib"
# The entry is built from the copy too: `ae build` resolves modules beside the
# source file's own tree before --lib, so building $ROOT/bin/… would pick up
# the repo's empty stub (measured: the result reported "not embedded").
mkdir -p "$WORK/bin"
cp "$ROOT/bin/aeo-agent.ae" "$WORK/bin/aeo-agent.ae"
{
    echo "// GENERATED by tools/build-agent.sh — a build product, never committed."
    echo "exports ( b64, sha256, built_from )"
    echo
    echo "b64() -> string {"
    echo "    return <<AEOSANDBOXLIB"
    base64 -w 100 "$SO"
    echo "AEOSANDBOXLIB"
    echo "}"
    echo
    echo "sha256() -> string {"
    echo "    return \"$SHA\""
    echo "}"
    echo
    echo "built_from() -> string {"
    echo "    return \"$FROM\""
    echo "}"
} > "$WORK/lib/sandbox_preload_blob/module.ae"

case "$OUT" in /*) ;; *) OUT="$PWD/$OUT";; esac
( cd "$WORK" && ae build bin/aeo-agent.ae -o "$OUT" --lib lib "$@" )
# Never hand back a binary that does not carry what this script exists to put
# in it.
"$OUT" preload >/dev/null 2>&1 || { echo "build-agent.sh: built $OUT but it reports no embedded library" >&2; exit 1; }
echo "build-agent.sh: $OUT carries $SO"
echo "build-agent.sh:   sha256 $SHA ($FROM)"
